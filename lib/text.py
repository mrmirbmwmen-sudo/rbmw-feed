def fit50(t,extra):
    # добавить отличие в конец; при нехватке места убирать кузова/год с конца (кроме первого кода кузова)
    w=t.split()
    while len(' '.join(w+[extra]))>50:
        idx=[k for k,x in enumerate(w) if re.fullmatch(r'[EFGIU]\d\d|20[12]\d',x)]
        if len(idx)<=1: break
        w.pop(idx[-1])
    r=' '.join(w+[extra])
    return r if len(r)<=50 else t
