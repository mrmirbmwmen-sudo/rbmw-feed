def gender(w):
    w=w.lower()
    if w in ('руль','привод','кулак','вал','рычаг','фонарь','люк','салон','двигатель','корпус','блок','насос'): return 'm'
    if w in ('дверь','ось','полуось','тяга'): return 'f'
    if re.search(r'(ы|и)$',w): return 'p'
    if re.search(r'(а|я)$',w): return 'f'
    if re.search(r'(о|е)$',w): return 'n'
    return 'm'
def clean_title(t):
    t=re.sub(r'\s+',' ',unent(t)).strip(); g=gender(t.split()[0]) if t else 'm'
    for pat,k in ABR:
        t=re.sub(r'(?i)\b'+pat+r'(?=\s|$)',lambda m:END[g][k],t)
    t=re.sub(r'№\s*\d+','',t)
    t=re.sub(r'(?<=\w)/(?=\w)',' ',t)
    t=re.sub(r"[,()\[\]/;:!«»\"№'’]+",' ',t)
    t=re.sub(r'(?i)(?<=\b20[12]\d)\s+(год|г\.?\s*в\.?|г\.?)(?=\s|$)','',t)
    t=re.sub(r'\s[-—–]\s',' ',t); t=re.sub(r'(?<=[А-Яа-я])\.(?=\s|$)','',t)
    t=re.sub(r'(?i)\s*\bв\s+сборе\b','',t)
    t=re.sub(r'\s+',' ',t).strip()
    if len(t)>50:
        w=t.split();
        while len(' '.join(w))>50: w.pop()
        t=' '.join(w)
    return t
def add_bodies(t,compat):
    allb=[]
    for x in re.findall(r'\b([EFGIU]\d\d)\b',str(compat or '')):
        if x not in allb: allb.append(x)
    extra=[b for b in allb if not re.search(r'\b'+b+r'\b',t)]
    if not extra: return t
    m=re.search(r'\s+(20[12]\d)\b',t); yr=m.group(1) if m else ''
    if yr: t=(t[:m.start()]+t[m.end():]).strip()
    # кузова ставим сразу после последнего кода кузова в заголовке
    last=None
    for mm in re.finditer(r'\b[EFGIU]\d\d\b(\s+LCI)?',t): last=mm
    head,tail=(t[:last.end()],t[last.end():]) if last else (t,'')
    for b in extra:
        if len(head+tail)+len(b)+1<=50: head=head+' '+b
    t=re.sub(r'\s+',' ',head+tail).strip()
    if yr and len(t)+5<=50: t=t+' '+yr
    return t
