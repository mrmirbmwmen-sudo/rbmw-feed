def unent(x):
    x=str(x or '')
    for _ in range(3):
        y=html.unescape(x)
        if y==x: break
        x=y
    x=re.sub(r'"([^"<>]{1,60})"',r'«\1»',x)        # "пустую" → «пустую»
    x=x.replace('"','')
    x=re.sub(r"(?<=\d)['’](?=\s)",'',x)            # BMW 5' M5 → BMW 5 M5
    x=x.replace("'",'').replace('’','')
    x=re.sub(r'\s*&\s*',' ',x)                     # Bowers & Wilkins → Bowers Wilkins
    return x

